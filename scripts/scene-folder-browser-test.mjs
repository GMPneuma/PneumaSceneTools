import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {fixture} from "./browser-fixture.mjs";
const {chromium}=await import(process.env.PNEUMA_PLAYWRIGHT_MODULE??"playwright");
const browser=await chromium.launch({headless:true,...(process.env.PNEUMA_BROWSER_CHANNEL?{channel:process.env.PNEUMA_BROWSER_CHANNEL}:{})});
try {
  const folderTree={maps:{files:[],dirs:['maps/pack','maps/empty']},'maps/pack':{files:['maps/pack/Factory-Map1.webp','maps/pack/Harbor.webp'],dirs:['maps/pack/sub']},'maps/pack/sub':{files:['maps/pack/sub/Harbor.webp','maps/pack/sub/Factory-Map2.webp'],dirs:[]},'maps/empty':{files:[],dirs:[]}};
  const {page,errors}=await fixture(browser,{files:[],folderTree,stayOnFolder:true});
  await page.addStyleTag({content:await readFile('dist/styles/pneuma-scenetools.css','utf8')});
  await page.addStyleTag({content:'body{width:700px;margin:16px;background:#eee;font:14px Arial}button,input,select{box-sizing:border-box}fieldset{min-width:0}button{width:100%}'});
  await page.screenshot({path:'docs/scene-wizard-folder-preview.png'});
  assert.equal(await page.locator('form').count(),2);
  assert.equal(await page.evaluate(()=>globalThis.pickerWindows??0),0);
  await page.locator('[data-native-folder] [data-path="maps/empty"]').click();
  await page.waitForFunction(()=>document.querySelector('[name=target]')?.value==='maps/empty');
  await page.locator('[data-folder-next]:enabled').click();
  await page.locator('[data-error]').filter({hasText:'Select a map image'}).waitFor();
  await page.locator('[data-native-folder] [data-action=back]').click();
  await page.evaluate(()=>globalThis.failBrowsePath='maps/pack');
  await page.locator('[data-native-folder] [data-path="maps/pack"]').click();
  await page.locator('[data-folder-status]').filter({hasText:'Folder unavailable'}).waitFor();
  await page.evaluate(()=>delete globalThis.failBrowsePath);
  await page.locator('[data-native-folder] [name=target]').fill('maps/pack');
  await page.locator('[data-native-folder] [name=target]').dispatchEvent('change');
  await page.locator('[data-native-folder] [data-path="maps/pack/sub"]').waitFor();
  assert.ok(await page.evaluate(()=>globalThis.nativePickerListeners>0));
  await page.waitForFunction(()=>document.querySelector('[name=target]')?.value==='maps/pack');
  await page.locator('[data-native-folder] [data-path="maps/pack/Factory-Map1.webp"]') .click();
  await page.evaluate(()=>globalThis.stallBrowsePath='maps/pack');
  await page.locator('[data-folder-next]:enabled').click();
  await page.locator('[data-cancel-scan]').click();
  await page.locator('[data-folder-status]').filter({hasText:'cancelled'}).waitFor();
  await page.evaluate(()=>{delete globalThis.stallBrowsePath;globalThis.finishBrowse();});
  await page.locator('[data-folder-next]:enabled').click();
  await page.locator('[name="variant-0"]').waitFor();
  assert.equal(await page.locator('[data-plan]').count(),2,'Only the selected filename family is included');
  await page.locator('[name=allVariants]').check();
  await page.locator('[data-back]').click();
  await page.locator('[name=target]:enabled').waitFor();
  await page.locator('[data-folder-next]:enabled').click();
  await page.locator('[name=allVariants]').waitFor();
  assert.equal(await page.locator('[name=allVariants]').isChecked(),true);
  await page.locator('button[type=submit]').click();
  await page.locator('[name="scene0-name"]').fill('Retained name');
  await page.locator('[data-back]').click();
  await page.locator('[name=allVariants]').waitFor();
  await page.locator('[data-back]').click();
  await page.locator('[name=target]:enabled').waitFor();
  await page.locator('[data-folder-next]:enabled').click();
  await page.locator('[name=allVariants]').waitFor();
  await page.locator('button[type=submit]').click();
  await page.locator('[name="scene0-name"]').waitFor();
  assert.equal(await page.locator('[name="scene0-name"]').inputValue(),'Retained name');
  await page.locator('[data-back]').click();
  await page.locator('[data-back]').click();
  await page.locator('[data-native-folder] [data-path="maps/pack/Harbor.webp"]') .click();
  await page.locator('[data-folder-next]:enabled').click();
  await page.locator('[name="variant-0"]') .waitFor();
  assert.equal(await page.locator('[data-plan]').count(),1);
  assert.match(await page.locator('[data-plan] legend').textContent(),/Harbor/);
  assert.equal(await page.evaluate(()=>globalThis.pickerWindows??0),0);
  assert.deepEqual(errors,[]);
  console.log('Inline folder navigation, recursive maps, empty-folder errors, cancellation and three-step Back retention passed.');
} finally {await browser.close();}
