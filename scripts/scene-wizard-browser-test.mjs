import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {fixture} from "./browser-fixture.mjs";
const {chromium} = await import(process.env.PNEUMA_PLAYWRIGHT_MODULE ?? "playwright");
const browser = await chromium.launch({headless:true, ...(process.env.PNEUMA_BROWSER_CHANNEL ? {channel:process.env.PNEUMA_BROWSER_CHANNEL} : {})});
try {
  const files = [1,2].map(n=>`maps/SOL-CorporateEateryInt-Map${n}-128px-4k.webp`);
  const {page,state,errors} = await fixture(browser,{selected:files[0],files});
  await page.addStyleTag({content:await readFile("dist/styles/pneuma-scenetools.css","utf8")});
  await page.addStyleTag({content:"body{width:1060px;margin:16px;background:#eee;font:14px Arial}button,input,select{box-sizing:border-box}fieldset{min-width:0}.form-group{display:flex}.form-group label{flex:1}.form-group input,.form-group select{flex:2}button{width:100%}"});
  const selects = await page.locator('[data-plan="0"] select').evaluateAll(items=>items.map(item=>({x:item.getBoundingClientRect().x,width:item.getBoundingClientRect().width})));
  assert.ok(selects.every(item=>item.x===selects[0].x && item.width===selects[0].width));
  assert.ok((await page.locator('[data-map-picker]').first().boundingBox()).width <= 64);
  await page.screenshot({path:"docs/scene-wizard-selection-preview.png"});
  await page.locator('[name="allVariants"]').check();
  await page.locator('button[type="submit"]').click();
  await page.locator('[name="scene0-name"]').fill("Edited scene");
  assert.equal(await page.locator('[data-image-asset]').count(),0);
  assert.equal(await page.getByText('Imported image paths',{exact:true}).count(),0);
  await page.locator('[name="scene0-darkness"]').fill("0.7");
  await page.locator('[name="scene0-tokenVision"]').uncheck();
  await page.locator('[name="applyShared"]').check();
  for (const field of ['Padding','Style','Thickness','Color','Opacity']) assert.equal(await page.locator(`[name="scene0-${field}"]`).isDisabled(),true);
  await page.locator('[name="sharedPadding"]').fill('30');
  await page.locator('[name="sharedThickness"]').fill('3');
  await page.locator('[name="sharedColor"]').fill('#123456');
  await page.locator('[name="sharedOpacity"]').fill('0.45');
  for (const index of [0,1]) for (const field of ['darkness','globalLight','tokenVision','fogExploration']) {
    assert.equal(await page.locator(`[name="scene${index}-${field}"]`).isDisabled(),true);
  }
  assert.equal(await page.locator('[name="scene0-name"]').isEnabled(),true);
  await page.locator('[name="applyShared"]').uncheck();
  assert.equal(await page.locator('[name="scene0-darkness"]').isEnabled(),true);
  assert.equal(await page.locator('[name="scene0-darkness"]').inputValue(),"0.7");
  assert.equal(await page.locator('[name="scene0-tokenVision"]').isChecked(),false);
  await page.locator('[name="applyShared"]').check();
  await page.locator('[name="sharedDarkness"]').fill("0.3");
  await page.locator('[data-select-scene="1"]').click();
  assert.equal(await page.locator('[data-scene="0"]').isVisible(),false);
  await page.locator('[name="scene1-name"]').fill("Second edit");
  await page.locator('[data-back]').click();
  await page.locator('[name="allVariants"]').waitFor();
  assert.equal(await page.locator('[name="allVariants"]').isChecked(),true);
  await page.locator('button[type="submit"]').click();
  await page.locator('[name="scene1-name"]').waitFor();
  assert.equal(await page.locator('[name="scene1-name"]').inputValue(),"Second edit");
  assert.equal(await page.locator('[name="scene0-name"]').inputValue(),"Edited scene");
  assert.equal(await page.locator('[name="sharedDarkness"]').inputValue(),"0.3");
  assert.equal(await page.locator('[name="scene1-darkness"]').isDisabled(),true);
  await page.locator('[name="scene1-darkness"]').evaluate(input=>input.scrollIntoView());
  await page.screenshot({path:"docs/scene-wizard-review-preview.png"});
  assert.ok((await page.locator('.pneuma-shared-settings').boundingBox()).height<190);
  const darkStyle=await page.addStyleTag({content:'body{--cpr-background-window:#232b2b;background:#232b2b;color:#ddd}select,option{background:#232b2b;color:#eee}'});
  assert.equal(await page.locator('.pneuma-wizard-footer').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(35, 43, 43)');
  assert.equal(await page.locator('[name="sharedStyle"]').evaluate(el=>getComputedStyle(el).color),'rgb(238, 238, 238)');
  assert.equal(await page.locator('[name="sharedStyle"] option').first().evaluate(el=>getComputedStyle(el).color),'rgb(238, 238, 238)');
  await page.locator('.pneuma-shared-settings').evaluate(el=>el.scrollIntoView());
  await page.screenshot({path:'docs/scene-wizard-dark-preview.png'});
  await darkStyle.evaluate(el=>el.remove());

  await page.locator('[data-back]').click();
  await page.locator('[name="variant-1"]').uncheck();
  await page.locator('button[type="submit"]').click();
  await page.locator('[name="scene0-name"]').waitFor();
  assert.equal(await page.locator('[data-select-scene]').count(),1);
  assert.notEqual(await page.locator('[name="scene0-name"]').inputValue(),"Edited scene");
  assert.deepEqual(await page.locator('[name="scene0-distance"] option').allTextContents(),['1 m','2 m','4 m']);
  assert.equal(await page.locator('[name="scene0-units"]').count(),0);
  await page.locator('[name="scene0-distance"]').selectOption('4');
  assert.ok((await page.locator('[name="scene0-width"]').boundingBox()).width <= 90);
  await page.locator('[name="scene0-name"]').evaluate(input=>input.scrollIntoView());
  const mainBox = await page.locator('[data-scene="0"] .pneuma-scene-main').boundingBox();
  const notesBox = await page.locator('[data-scene="0"] .pneuma-scene-notes').boundingBox();
  const fieldsBox = await page.locator('[data-scene="0"] .pneuma-scene-fields').boundingBox();
  const previewBox = await page.locator('[data-scene="0"] .pneuma-grid-preview').boundingBox();
  assert.ok(previewBox.x >= fieldsBox.x + fieldsBox.width);
  assert.ok(previewBox.height > 160);
  assert.ok(notesBox.x >= fieldsBox.x + fieldsBox.width);
  assert.ok(notesBox.y >= previewBox.y + previewBox.height);
  assert.ok((await page.locator('[name="scene0-name"]').boundingBox()).width >= fieldsBox.width - 2);
  assert.equal(await page.locator('[data-scene="0"] .pneuma-import-details').first().evaluate(el=>el.open),false);
  assert.equal(await page.locator('[data-scene="0"] .pneuma-import-counts dd').count(),3);
  await page.setViewportSize({width:1440,height:1000});
  await page.addStyleTag({content:'body{width:1380px;margin:20px}.pneuma-scene-creator-window{height:940px}.pneuma-scene-creator-window form{height:940px}'});
  await page.locator('form').evaluate(form=>form.parentElement.classList.add('pneuma-scene-creator-window'));
  await page.locator('.pneuma-scene-editor').evaluate(el=>el.scrollTop=0);
  await page.screenshot({path:"docs/scene-wizard-compact-fields-preview.png"});
  await page.locator('button[type="submit"]').click();
  await page.waitForFunction(()=>!document.querySelector('form'));
  assert.equal((await state()).scenes.length,1);
  assert.equal((await state()).scenes[0].grid.distance,4);
  assert.equal((await state()).scenes[0].grid.units,'m');
  assert.equal((await state()).scenes[0].padding,0.25);
  assert.deepEqual(errors,[]);
  console.log("Wizard alignment, scene switching, Back state retention, changed assignments and save passed.");
} finally {await browser.close();}
